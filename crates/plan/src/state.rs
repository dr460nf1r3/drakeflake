use std::collections::{BTreeMap, BTreeSet};
use std::io::{self, ErrorKind};
use std::path::{Path, PathBuf};
use std::{fmt, fs};

use drakeflake_render::{OptionName, PackageAttr};
use log::debug;
use serde::{Deserialize, Serialize};

use crate::header::{FILE_NAME, state_line};
use crate::option::ManagedOption;

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ManagedState {
    #[serde(default)]
    pub options: BTreeMap<OptionName, ManagedOption>,
    #[serde(default)]
    pub packages: BTreeSet<PackageAttr>,
}

#[derive(Debug)]
pub enum StateError {
    Corrupt(serde_json::Error),
    Read { path: PathBuf, source: io::Error },
    NotGenerated(PathBuf),
}

impl ManagedState {
    #[must_use = "only checks the state"]
    pub fn is_empty(&self) -> bool {
        self.options.is_empty() && self.packages.is_empty()
    }

    #[must_use = "the parsed state is the only result"]
    pub fn parse(text: &str) -> Result<Option<Self>, StateError> {
        state_line(text).map_or(Ok(None), |line| {
            serde_json::from_str(line)
                .map(Some)
                .map_err(StateError::Corrupt)
        })
    }

    #[must_use = "the loaded state is the only result"]
    pub fn load(path: &Path) -> Result<Self, StateError> {
        let text = match fs::read_to_string(path) {
            Ok(text) => text,
            Err(err) if err.kind() == ErrorKind::NotFound => {
                debug!("no managed file at {} yet", path.display());
                return Ok(Self::default());
            }
            Err(source) => {
                return Err(StateError::Read {
                    path: path.to_path_buf(),
                    source,
                });
            }
        };

        match Self::parse(&text)? {
            Some(state) => {
                debug!(
                    "loaded managed state from {}: {} options, {} packages",
                    path.display(),
                    state.options.len(),
                    state.packages.len()
                );
                Ok(state)
            }
            None if text.trim().is_empty() => Ok(Self::default()),
            None => Err(StateError::NotGenerated(path.to_path_buf())),
        }
    }
}

impl fmt::Display for StateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Corrupt(err) => write!(f, "corrupt state line in {FILE_NAME}: {err}"),
            Self::Read { path, source } => {
                write!(f, "cannot read {}: {source}", path.display())
            }
            Self::NotGenerated(path) => write!(
                f,
                "{} exists but was not generated by DrakeFlake, so it is never overwritten; move or rename it, or choose another output file in Settings",
                path.display()
            ),
        }
    }
}

impl std::error::Error for StateError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Corrupt(err) => Some(err),
            Self::Read { path: _, source } => Some(source),
            Self::NotGenerated(_) => None,
        }
    }
}

pub fn check_state_line(text: &str) -> Result<(), StateError> {
    ManagedState::parse(text).map(drop)
}
