#[test]
fn content_is_refused_before_the_parser_runs() {
    let temp = tempfile::tempdir().unwrap();
    let flake = temp.path().canonicalize().unwrap();
    fs::write(flake.join("flake.nix"), "{ }").unwrap();
    let corrupt_state = format!("{HEADER}{STATE_PREFIX}{{\"packages\": 1}}\n{{ }}\n");

    for (text, reason) in [
        ("{ }", "the content is not a DrakeFlake module"),
        (corrupt_state.as_str(), "corrupt state line"),
    ] {
        let plan = WritePlan {
            write: [(flake.join("new.nix"), text.to_owned())].into(),
            remove: Vec::new(),
        };

        let refused = plan.validate().unwrap_err().to_string();
        assert!(
            refused.starts_with(&format!("{}: {reason}", flake.join("new.nix").display())),
            "{refused}"
        );
    }
}

#[test]
fn header_lines_are_only_read_from_the_header() {
    let filler = "#\n".repeat(10);
    let late = format!("{HEADER}{filler}{STATE_PREFIX}{{}}\n");
    assert_eq!(state_line(&late), None);
    assert_eq!(
        state_line(&format!("{HEADER}{STATE_PREFIX}{{}}\n")),
        Some("{}")
    );

    let corrupt = format!("{HEADER}{FILES_PREFIX}[\"a.nix\"\n");
    assert_eq!(generated_files(&corrupt), Vec::<PathBuf>::new());
    assert!(!has_generated_header(&format!(" {HEADER}")));
}

