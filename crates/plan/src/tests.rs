#[test]
fn plans_remove_parts_the_new_entry_no_longer_has() {
    let previous = format!("{HEADER}{FILES_PREFIX}[\"parts/a.nix\",\"parts/b.nix\"]\n");
    let rendered = Rendered {
        entry: HEADER.to_owned(),
        parts: vec![RenderedFile {
            path: PathBuf::from("parts/a.nix"),
            text: HEADER.to_owned(),
        }],
    };

    let plan = WritePlan::for_rendered(
        Path::new("/f/e.nix"),
        &rendered,
        Some(&previous),
        Path::new("/f/parts"),
    );

    assert_eq!(
        plan.write.keys().collect::<Vec<_>>(),
        [Path::new("/f/e.nix"), Path::new("/f/parts/a.nix")]
    );
    assert_eq!(plan.remove, [PathBuf::from("/f/parts/b.nix")]);
}

#[test]
fn syntax_runner_failures_are_reported() {
    let run = |success: bool, stderr: &str| SyntaxRun {
        success,
        stderr: stderr.to_owned(),
    };

    let err = check_syntax_with("{ }", |_, _, _| Ok(run(false, " bad\n"))).unwrap_err();
    assert!(
        matches!(&err, SyntaxError::Invalid(message) if message == "bad"),
        "{err}"
    );
    check_syntax_with("{ }", |_, _, _| Ok(run(true, ""))).unwrap();
}

#[test]
fn the_parse_check_reads_the_text_from_stdin() {
    let result = check_syntax_with("{ a = 1; }", |program, args, input| {
        assert_eq!(program, "nix-instantiate");
        assert_eq!(args, ["--parse", "-"]);
        assert_eq!(input, "{ a = 1; }");
        Err("cannot run nix-instantiate".into())
    });

    let err = result.unwrap_err();
    assert!(matches!(err, SyntaxError::Run(_)), "{err}");
    assert_eq!(err.to_string(), "cannot run nix-instantiate");
}

