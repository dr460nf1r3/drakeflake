#[test]
fn write_target_checks_keep_their_order_and_messages() {
    let refused = |path: &str| check_write_target(Path::new(path)).unwrap_err().to_string();

    assert_eq!(refused("x/../y"), "the target must be an absolute path");
    assert_eq!(refused("/x/../y.nix"), "the target must not contain '..'");
    assert_eq!(refused("/x/y.txt"), "the target must be a .nix file");

    // The real folder is named: `/etc` is `/private/etc` on macOS.
    let etc = Path::new("/etc").canonicalize().unwrap();
    assert_eq!(
        refused("/etc/x.nix"),
        format!("{} is not inside a flake", etc.display())
    );

    let temp = tempfile::tempdir().unwrap();
    let flake = temp.path().canonicalize().unwrap();
    fs::write(flake.join("flake.nix"), "{ }").unwrap();
    fs::create_dir_all(flake.join("dir.nix")).unwrap();
    assert!(matches!(
        check_write_target(&flake.join("dir.nix")),
        Err(Refusal::NotRegularFile)
    ));
    assert_eq!(
        check_write_target(&flake.join("flake.nix"))
            .unwrap_err()
            .to_string(),
        format!(
            "{} was not generated by DrakeFlake; refusing to overwrite it",
            flake.join("flake.nix").display()
        )
    );
}

#[test]
fn refusals_are_variants_and_io_failures_keep_their_kind() {
    assert!(matches!(
        check_write_target(Path::new("x.nix")),
        Err(Refusal::NotAbsolute)
    ));
    assert!(matches!(
        check_write_target(Path::new("/x/y.txt")),
        Err(Refusal::NotNixFile)
    ));

    let temp = tempfile::tempdir().unwrap();
    let missing = temp.path().join("flake.nix").join("a.nix");
    fs::write(temp.path().join("flake.nix"), "{ }").unwrap();

    let error = check_local_write_target(&missing).unwrap_err();
    assert_eq!(error.io_kind(), Some(ErrorKind::NotADirectory), "{error}");

    let wrapped = Refusal::inspect(
        Path::new("/x.nix"),
        io::Error::from(ErrorKind::PermissionDenied),
    )
    .in_file(Path::new("/x.nix"));

    assert_eq!(wrapped.io_kind(), Some(ErrorKind::PermissionDenied));
    assert_eq!(Refusal::NotModule.io_kind(), None);
}

#[test]
fn flake_root_is_the_nearest_flake() {
    let temp = tempfile::tempdir().unwrap();
    let nested = temp.path().join("a/b");
    fs::create_dir_all(&nested).unwrap();
    assert_eq!(find_flake_root(&nested), None);

    fs::write(temp.path().join("a/flake.nix"), "{ }").unwrap();
    assert_eq!(find_flake_root(&nested), Some(temp.path().join("a")));
}

