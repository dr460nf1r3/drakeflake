#[test]
fn local_validation_needs_no_flake_but_keeps_the_other_rules() {
    let temp = tempfile::tempdir().unwrap();
    let dir = temp.path().canonicalize().unwrap();
    fs::write(dir.join("theirs.nix"), "{ }").unwrap();
    fs::write(dir.join("ours.nix"), HEADER).unwrap();
    std::os::unix::fs::symlink(dir.join("ours.nix"), dir.join("link.nix")).unwrap();

    let plan = |write: &[(&str, &str)], remove: &[&str]| WritePlan {
        write: write
            .iter()
            .map(|(name, text)| (dir.join(name), (*text).to_owned()))
            .collect(),
        remove: remove.iter().map(|name| dir.join(name)).collect(),
    };

    plan(&[("new.nix", HEADER)], &["ours.nix", "gone.nix"])
        .validate_local()
        .unwrap();
    plan(&[("new.nix", HEADER)], &[]).validate().unwrap_err();

    for refused in [
        plan(&[("theirs.nix", HEADER)], &[]),
        plan(&[("link.nix", HEADER)], &[]),
        plan(&[("new.nix", "{ }")], &[]),
        plan(&[], &["theirs.nix"]),
        plan(&[], &["link.nix"]),
        plan(&[("new.txt", HEADER)], &[]),
    ] {
        assert!(refused.clone().validate_local().is_err(), "{refused:?}");
    }
}

