#[test]
fn the_entry_is_written_last() {
    let temp = tempfile::tempdir().unwrap();
    let dir = temp.path().canonicalize().unwrap();
    let entry = format!("{HEADER}{STATE_PREFIX}{{}}\n");
    let plan = WritePlan {
        write: [
            (dir.join("a.nix"), entry),
            (dir.join("z.nix"), HEADER.to_owned()),
        ]
        .into(),
        remove: Vec::new(),
    };

    let validated = plan.validate_local().unwrap();
    let order: Vec<&Path> = validated
        .ordered_writes()
        .into_iter()
        .map(|(path, _)| path)
        .collect();

    assert_eq!(order, [dir.join("z.nix"), dir.join("a.nix")]);
    assert_eq!(validated.removals(), Vec::<PathBuf>::new());
}

#[test]
fn a_file_cannot_be_written_and_removed() {
    let temp = tempfile::tempdir().unwrap();
    let flake = temp.path().canonicalize().unwrap();
    let file = flake.join("a.nix");
    let plan = WritePlan {
        write: [(file.clone(), HEADER.to_owned())].into(),
        remove: vec![file],
    };

    for refused in [
        plan.clone().validate().unwrap_err(),
        plan.validate_local().unwrap_err(),
    ] {
        assert!(
            matches!(
                &refused,
                Refusal::InFile { path: _, cause } if matches!(**cause, Refusal::BothWrittenAndRemoved)
            ),
            "{refused}"
        );
        assert!(refused.to_string().ends_with("both written and removed"));
    }
}

