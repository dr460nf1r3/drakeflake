use std::fmt;
use std::io::{self, ErrorKind};
use std::path::{Path, PathBuf};

use crate::state::StateError;
use crate::syntax::SyntaxError;

/// Shared by the helper and the app's writer, so a policy decision is told apart from an I/O failure.
#[derive(Debug)]
pub enum Refusal {
    NotAbsolute,
    ParentDir,
    NotNixFile,
    NoExistingParent,
    InNixStore(PathBuf),
    NotInFlake(PathBuf),
    NotRegularFile,
    NotRemovable,
    NotGenerated(PathBuf),
    NotModule,
    BothWrittenAndRemoved,
    DuplicateTarget,
    TooManyFiles(usize),
    State(StateError),
    Syntax(SyntaxError),
    Io {
        action: &'static str,
        path: PathBuf,
        source: io::Error,
    },
    InFile {
        path: PathBuf,
        cause: Box<Self>,
    },
}

impl Refusal {
    #[must_use = "only reads the error kind"]
    pub fn io_kind(&self) -> Option<ErrorKind> {
        match self {
            Self::Io {
                action: _,
                path: _,
                source,
            }
            | Self::State(StateError::Read { path: _, source }) => Some(source.kind()),
            Self::InFile { path: _, cause } => cause.io_kind(),
            Self::Syntax(_)
            | Self::State(_)
            | Self::NotAbsolute
            | Self::ParentDir
            | Self::NotNixFile
            | Self::NoExistingParent
            | Self::InNixStore(_)
            | Self::NotInFlake(_)
            | Self::NotRegularFile
            | Self::NotRemovable
            | Self::NotGenerated(_)
            | Self::NotModule
            | Self::BothWrittenAndRemoved
            | Self::DuplicateTarget
            | Self::TooManyFiles(_) => None,
        }
    }

    pub(crate) fn inspect(path: &Path, source: io::Error) -> Self {
        Self::io("inspect", path, source)
    }

    pub(crate) fn io(action: &'static str, path: &Path, source: io::Error) -> Self {
        Self::Io {
            action,
            path: path.to_path_buf(),
            source,
        }
    }

    #[must_use = "only wraps the refusal"]
    pub fn in_file(self, path: &Path) -> Self {
        Self::InFile {
            path: path.to_path_buf(),
            cause: Box::new(self),
        }
    }
}

impl fmt::Display for Refusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NotAbsolute => f.write_str("the target must be an absolute path"),
            Self::ParentDir => f.write_str("the target must not contain '..'"),
            Self::NotNixFile => f.write_str("the target must be a .nix file"),
            Self::NoExistingParent => f.write_str("the target has no existing parent directory"),
            Self::InNixStore(path) => write!(f, "{} is in the Nix store", path.display()),
            Self::NotInFlake(path) => write!(f, "{} is not inside a flake", path.display()),
            Self::NotRegularFile => f.write_str("the target exists and is not a regular file"),
            Self::NotRemovable => f.write_str("only regular files can be removed"),
            Self::NotGenerated(path) => write!(
                f,
                "{} was not generated by DrakeFlake; refusing to overwrite it",
                path.display()
            ),
            Self::NotModule => f.write_str("the content is not a DrakeFlake module"),
            Self::BothWrittenAndRemoved => f.write_str("the file is both written and removed"),
            Self::DuplicateTarget => {
                f.write_str("more than one file in the plan resolves to this path")
            }
            Self::TooManyFiles(count) => {
                write!(
                    f,
                    "the plan names {count} files, which is too many for one Apply"
                )
            }
            Self::State(error) => error.fmt(f),
            Self::Syntax(error) => error.fmt(f),
            Self::Io {
                action,
                path,
                source,
            } => write!(f, "cannot {action} {}: {source}", path.display()),
            Self::InFile { path, cause } => write!(f, "{}: {cause}", path.display()),
        }
    }
}

impl std::error::Error for Refusal {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Io {
                action: _,
                path: _,
                source,
            } => Some(source),
            Self::InFile { path: _, cause } => Some(cause.as_ref()),
            Self::State(error) => Some(error),
            Self::Syntax(error) => Some(error),
            Self::NotAbsolute
            | Self::ParentDir
            | Self::NotNixFile
            | Self::NoExistingParent
            | Self::InNixStore(_)
            | Self::NotInFlake(_)
            | Self::NotRegularFile
            | Self::NotRemovable
            | Self::NotGenerated(_)
            | Self::NotModule
            | Self::BothWrittenAndRemoved
            | Self::DuplicateTarget
            | Self::TooManyFiles(_) => None,
        }
    }
}

impl From<StateError> for Refusal {
    fn from(error: StateError) -> Self {
        Self::State(error)
    }
}

impl From<SyntaxError> for Refusal {
    fn from(error: SyntaxError) -> Self {
        Self::Syntax(error)
    }
}
