use std::path::{Component, PathBuf};

use log::warn;

pub const FILE_NAME: &str = "drakeflake.nix";

/// Marks a file as ours: only such files may be overwritten or removed.
pub const HEADER: &str = "# GENERATED by DrakeFlake - safe to delete.\n\
     # Hand edits inside this file are overwritten on next Apply.\n";

pub const STATE_PREFIX: &str = "# drakeflake-state: ";
pub const FILES_PREFIX: &str = "# drakeflake-files: ";
/// Bounds the search for the state and file list lines, which sit in the header.
const HEADER_SCAN_LINES: usize = 10;

#[must_use = "only checks the text"]
pub fn has_generated_header(text: &str) -> bool {
    text.starts_with(HEADER)
}

fn header_line<'text>(text: &'text str, prefix: &str) -> Option<&'text str> {
    text.lines()
        .take(HEADER_SCAN_LINES)
        .find_map(|line| line.strip_prefix(prefix))
}

#[must_use = "the line is only looked up"]
pub fn state_line(text: &str) -> Option<&str> {
    header_line(text, STATE_PREFIX)
}

/// The header is plain text anyone can edit, so only names below the entry's
/// directory are believed.
fn relative_entry(file: &str) -> Option<PathBuf> {
    let path = PathBuf::from(file);
    let below = !path.as_os_str().is_empty()
        && path
            .components()
            .all(|part| matches!(part, Component::Normal(_)));

    if below {
        Some(path)
    } else {
        warn!("ignoring file list entry \"{file}\" in {FILE_NAME}: not below the entry's folder");
        None
    }
}

#[must_use = "the header is only parsed"]
pub fn generated_files(entry_text: &str) -> Vec<PathBuf> {
    let Some(json) = header_line(entry_text, FILES_PREFIX) else {
        return Vec::new();
    };

    match serde_json::from_str::<Vec<String>>(json) {
        Ok(files) => files
            .into_iter()
            .filter_map(|file| relative_entry(&file))
            .collect(),
        Err(err) => {
            warn!("ignoring corrupt file list in {FILE_NAME}: {err}");
            Vec::new()
        }
    }
}
