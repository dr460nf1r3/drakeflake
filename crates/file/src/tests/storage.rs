fn files_in(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .collect();

    names.sort();
    names
}

#[test]
fn backups_in_the_same_second_do_not_overwrite_each_other() {
    let dir = tempfile::tempdir().unwrap();
    let managed = dir.path().join(FILE_NAME);
    let backups = dir.path().join("state/backups");

    fs::write(&managed, "first").unwrap();
    let first = backup_to(&managed, &backups).unwrap().unwrap();
    fs::write(&managed, "second").unwrap();
    let second = backup_to(&managed, &backups).unwrap().unwrap();

    assert_ne!(first, second);
    assert_eq!(fs::read_to_string(&first).unwrap(), "first");
    assert_eq!(fs::read_to_string(&second).unwrap(), "second");
    let name = file_name_of(&second);
    assert!(
        name.starts_with("drakeflake.nix.") && second.extension().is_some_and(|ext| ext == "bak"),
        "{name}"
    );

    let blocker = dir.path().join("blocker");
    fs::write(&blocker, "").unwrap();
    let error = backup_to(&managed, &blocker.join("backups")).unwrap_err();
    assert!(error.to_string().starts_with("cannot create"), "{error}");
    assert!(
        matches!(error, FileError::BackupDir { dir: _, source: _ }),
        "{error}"
    );
}

#[test]
fn loading_tells_empty_corrupt_and_unreadable_files_apart() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join(FILE_NAME);

    fs::write(&path, "  \n").unwrap();
    assert_eq!(ManagedState::load(&path).unwrap(), ManagedState::default());

    fs::write(&path, format!("{HEADER}{STATE_PREFIX}{{\"options\": 3}}\n")).unwrap();
    let corrupt = ManagedState::load(&path).unwrap_err();
    assert!(
        corrupt.to_string().starts_with("corrupt state line"),
        "{corrupt}"
    );

    fs::write(&path, "{ services.openssh.enable = true; }\n").unwrap();
    let foreign = ManagedState::load(&path).unwrap_err();
    assert!(
        foreign.to_string().contains("never overwritten"),
        "{foreign}"
    );

    let unreadable = ManagedState::load(dir.path()).unwrap_err();
    assert!(
        unreadable.to_string().starts_with("cannot read"),
        "{unreadable}"
    );
}

#[test]
fn removals_tolerate_missing_files_and_keep_used_folders() {
    let dir = tempfile::tempdir().unwrap();
    let parts = dir.path().join("drakeflake");
    fs::create_dir_all(&parts).unwrap();
    fs::write(parts.join("a.nix"), HEADER).unwrap();
    fs::write(parts.join("b.nix"), HEADER).unwrap();

    let plan = WritePlan {
        write: std::collections::BTreeMap::new(),
        remove: vec![parts.join("a.nix"), parts.join("gone.nix")],
    };

    apply_direct(&plan.validate_local().unwrap()).unwrap();

    assert_eq!(files_in(&parts), ["b.nix"]);
}

