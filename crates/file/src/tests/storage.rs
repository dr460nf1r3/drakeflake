#[test]
fn only_permission_errors_ask_for_root() {
    let dir = tempfile::tempdir().unwrap();
    let blocker = dir.path().join("blocker");
    fs::write(&blocker, "").unwrap();
    let plan = WritePlan {
        write: [(blocker.join("drakeflake.nix"), HEADER.to_owned())].into(),
        remove: Vec::new(),
    };

    let error = write_files(&Context::system(), &plan, None).unwrap_err();

    assert!(
        error.to_string().starts_with("cannot write the settings"),
        "{error}"
    );
    assert!(!error.is_permission_denied(), "{error}");
}

/// A mode of 0 does not stop root, whose runs cannot tell the cases apart.
fn is_restricted(path: &Path) -> bool {
    fs::read(path).is_err()
}

#[test]
fn a_refused_plan_does_not_ask_for_root() {
    let dir = tempfile::tempdir().unwrap();
    let theirs = dir.path().join("theirs.nix");
    fs::write(&theirs, "{ keep = true; }").unwrap();
    let plan = generated_plan(&[(&theirs, HEADER)], &[]);

    let error = write_files(&Context::system(), &plan, None).unwrap_err();

    assert!(matches!(&error, FileError::Refused(_)), "{error}");
    assert!(
        error
            .to_string()
            .contains("was not generated by DrakeFlake"),
        "{error}"
    );
    assert_eq!(fs::read_to_string(&theirs).unwrap(), "{ keep = true; }");
}

#[test]
fn a_target_that_cannot_be_read_asks_for_root() {
    use std::os::unix::fs::PermissionsExt as _;

    let dir = tempfile::tempdir().unwrap();
    let ours = dir.path().join("ours.nix");
    fs::write(&ours, HEADER).unwrap();
    fs::set_permissions(&ours, fs::Permissions::from_mode(0o0)).unwrap();
    let plan = generated_plan(&[(&ours, HEADER)], &[]);

    if is_restricted(&ours) {
        let error = write_files(&Context::system(), &plan, None).unwrap_err();

        assert!(matches!(error, FileError::NoHelper), "{error}");
    }

    fs::set_permissions(&ours, fs::Permissions::from_mode(0o644)).unwrap();
}

#[test]
fn a_folder_that_cannot_be_written_asks_for_root() {
    use std::os::unix::fs::PermissionsExt as _;

    let dir = tempfile::tempdir().unwrap();
    let folder = dir.path().join("locked");
    fs::create_dir_all(&folder).unwrap();
    fs::set_permissions(&folder, fs::Permissions::from_mode(0o555)).unwrap();
    let plan = generated_plan(&[(&folder.join("new.nix"), HEADER)], &[]);

    if fs::write(folder.join("probe"), "").is_err() {
        let error = write_files(&Context::system(), &plan, None).unwrap_err();

        assert!(matches!(error, FileError::NoHelper), "{error}");
    }

    fs::set_permissions(&folder, fs::Permissions::from_mode(0o755)).unwrap();
}

#[test]
fn the_import_scan_skips_hidden_build_and_too_deep_folders() {
    let flake = tempfile::tempdir().unwrap();
    let managed = flake.path().join(FILE_NAME);
    fs::write(&managed, HEADER).unwrap();
    let importer = |dir: &str| -> PathBuf {
        let folder = flake.path().join(dir);
        fs::create_dir_all(&folder).unwrap();
        let depth = dir.split('/').count();
        let up = "../".repeat(depth);
        fs::write(
            folder.join("host.nix"),
            format!("{{ imports = [ {up}drakeflake.nix ]; }}"),
        )
        .unwrap();
        folder
    };

    for skipped in [".git", "result", "node_modules", "a/b/c/d/e"] {
        let folder = importer(skipped);
        assert!(!is_imported(flake.path(), &managed), "{skipped}");
        fs::remove_dir_all(folder).unwrap();
    }

    importer("a/b/c/d");
    assert!(is_imported(flake.path(), &managed));
}

#[test]
fn a_symlinked_module_is_found_by_the_scan() {
    let flake = tempfile::tempdir().unwrap();
    let managed = flake.path().join(FILE_NAME);
    fs::write(&managed, HEADER).unwrap();
    let outside = tempfile::tempdir().unwrap();
    let real = outside.path().join("host.nix");
    fs::write(&real, "{ imports = [ ./drakeflake.nix ]; }").unwrap();
    std::os::unix::fs::symlink(&real, flake.path().join("host.nix")).unwrap();

    assert!(is_imported(flake.path(), &managed));
}

#[test]
fn a_symlink_to_a_pipe_is_not_read_by_the_scan() {
    let flake = tempfile::tempdir().unwrap();
    let managed = flake.path().join(FILE_NAME);
    fs::write(&managed, HEADER).unwrap();
    let pipe = flake.path().join("pipe");
    let made = std::process::Command::new("mkfifo").arg(&pipe).status();

    if made.is_ok_and(|status| status.success()) {
        std::os::unix::fs::symlink(&pipe, flake.path().join("host.nix")).unwrap();

        assert!(!is_imported(flake.path(), &managed));
    }
}

#[test]
fn only_a_lowercase_nix_extension_counts() {
    let rules = LayoutConfig::parse_rules("a = Remote.NIX\nb = fine.nix").unwrap();
    let files: Vec<&str> = rules.iter().map(LayoutRule::file).collect();

    assert_eq!(files, ["Remote.NIX.nix", "fine.nix"]);
}

fn generated_plan(files: &[(&Path, &str)], remove: &[&Path]) -> WritePlan {
    WritePlan {
        write: files
            .iter()
            .map(|(path, text)| (path.to_path_buf(), (*text).to_owned()))
            .collect(),
        remove: remove.iter().map(|path| path.to_path_buf()).collect(),
    }
}

#[test]
fn the_direct_writer_refuses_what_the_helper_would() {
    let dir = tempfile::tempdir().unwrap();
    let ours = dir.path().join("ours.nix");
    let theirs = dir.path().join("theirs.nix");
    let link = dir.path().join("link.nix");
    fs::write(&ours, HEADER).unwrap();
    fs::write(&theirs, "{ keep = true; }").unwrap();
    std::os::unix::fs::symlink(&ours, &link).unwrap();
    let fresh = dir.path().join("fresh.nix");

    for plan in [
        generated_plan(&[(&fresh, HEADER), (&theirs, HEADER)], &[]),
        generated_plan(&[(&fresh, HEADER), (&link, HEADER)], &[]),
        generated_plan(&[(&fresh, "{ not-generated = 1; }")], &[]),
        generated_plan(&[(&fresh, HEADER)], &[&theirs]),
        generated_plan(&[(&fresh, HEADER)], &[&link]),
        generated_plan(&[(Path::new("relative.nix"), HEADER)], &[]),
        generated_plan(&[(&dir.path().join("../up.nix"), HEADER)], &[]),
        generated_plan(&[(&dir.path().join("x.txt"), HEADER)], &[]),
    ] {
        let error = plan.clone().validate_local().unwrap_err();

        assert_eq!(error.io_kind(), None, "{plan:?}: {error}");
        assert!(
            matches!(
                write_files(&Context::system(), &plan, None),
                Err(FileError::Refused(_))
            ),
            "{plan:?}"
        );
    }

    assert_eq!(files_in(dir.path()), ["link.nix", "ours.nix", "theirs.nix"]);
    assert_eq!(fs::read_to_string(&theirs).unwrap(), "{ keep = true; }");
}

#[test]
fn the_entry_is_swapped_in_after_the_parts() {
    let dir = tempfile::tempdir().unwrap();
    let entry = dir.path().join("a-entry.nix");
    let part = dir.path().join("z-part.nix");
    let entry_text = format!("{HEADER}{STATE_PREFIX}{{}}\n");

    let plan = generated_plan(&[(&entry, &entry_text), (&part, HEADER)], &[]);
    apply_direct(&plan.validate_local().unwrap()).unwrap();

    assert_eq!(fs::read_to_string(&entry).unwrap(), entry_text);
    assert_eq!(files_in(dir.path()), ["a-entry.nix", "z-part.nix"]);
}

